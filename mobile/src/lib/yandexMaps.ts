// Маршрут в Яндекс.Картах по адресам точек заказа (раздел 7 ТЗ). Строим
// маршрут строго между точками заказа, без «от меня» (пустая первая точка
// в rtext раньше открывала приложение без построения маршрута — репорт с
// реального устройства).
//
// mode=routes раньше добавляли, чтобы явно включить в Картах режим
// построения маршрута — на деле именно это на реальном iPhone открывало
// приложение на пустом экране режима «маршруты» БЕЗ резолва точек из rtext
// (доработки 3, п.8). У web-кабинета тот же rtext без mode=routes и маршрут
// строится нормально — параметры совпадают.
//
// 30.09: Максим сообщил, что маршрут по-прежнему не строится с телефона —
// открываются только сами Карты. Обе прошлые правки трогали только
// параметры ЭТОЙ ссылки (yandex.ru/maps, universal link) — если
// установленное приложение Яндекс.Карт перехватывает такую ссылку через
// Android/iOS App Links СВОИМ способом (не как сайт), параметры маршрута
// могут не долетать до него так же, как до браузера. Пробуем ДРУГОЙ путь:
// собственная URI-схема приложения (yandexmaps://) с теми же rtext/rtt —
// по документации Яндекса предназначена именно для построения маршрута
// внутри приложения, в отличие от универсальной ссылки. Открываем её
// первой, а обычную https-ссылку — только запасным вариантом, если схема
// не обработана (Яндекс.Карты не установлены). Не проверено на реальном
// устройстве (два предыдущих исправления тоже казались рабочими и не
// подтвердились) — нужна проверка на телефоне.
export function yandexMapsRouteUrl(addresses: string[]) {
  const points = addresses.map((a) => encodeURIComponent(a)).join('~');
  return `https://yandex.ru/maps/?rtext=${points}&rtt=auto`;
}

export function yandexMapsRouteAppUrl(addresses: string[]) {
  const points = addresses.map((a) => encodeURIComponent(a)).join('~');
  return `yandexmaps://maps.yandex.ru/?rtext=${points}&rtt=auto`;
}
