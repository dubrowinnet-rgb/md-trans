// Маршрут в Яндекс.Картах по адресам точек заказа (раздел 7 ТЗ). На
// телефоне с установленными Яндекс.Картами ссылка открывает приложение,
// иначе сайт. Раньше первой точкой в rtext стояла пустая строка («от
// моего местоположения») — с ней открывалось само приложение, но маршрут
// не строился (репорт с реального устройства): судя по всему, нативное
// приложение не умеет резолвить пустой сегмент так же, как сайт. Строим
// маршрут строго между точками заказа, без «от меня», и добавляем
// mode=routes, который явно переключает Карты в режим построения
// маршрута, а не просто открывает точку на карте. Прямой deep link в
// Яндекс.Навигатор с координатами (без этого шага, но с геокодером и
// API-ключом Яндекса) остаётся более надёжным следующим шагом, если это
// тоже не заработает на реальном устройстве.
export function yandexMapsRouteUrl(addresses: string[]) {
  const points = addresses.map((a) => encodeURIComponent(a)).join('~');
  return `https://yandex.ru/maps/?rtext=${points}&rtt=auto&mode=routes`;
}
